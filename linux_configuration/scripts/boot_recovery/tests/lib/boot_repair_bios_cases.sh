#!/bin/bash

# ============================================================================
# boot-repair fixture cases: BIOS/GRUB firmware guard (GUARD 3).
#
# Split out of boot_repair_cases.sh, which is at the 250-line cap. Sourced by
# test_boot_repair.sh and relies on the helpers defined there (make_root,
# run_repair, assert_*).
#
# The bug these cover was measured on 2026-08-22 in a vmbox sandbox: on a
# BIOS/GRUB guest with no ESP, boot-repair read the real /boot/vmlinuz-linux
# and /boot/initramfs-linux.img as "orphaned kernel file(s) shadowing the ESP"
# and deleted them. The guest never booted again.
# ============================================================================

# A BIOS box, shaped exactly like the guest that lost its kernel: no
# sys/firmware/efi, and a /boot that holds the real kernel with no EFI/ or
# loader/ to trip GUARD 2.
make_bios_root() {
	local name="$1"
	local r
	r="$(make_root "$name" 7.1.5-arch1-2 bios)"

	# GRUB keeps its kernel in a plain /boot directory on the root filesystem.
	rm -rf "${r:?}/boot"
	mkdir -p "$r/boot/grub"
	printf 'Linux version 7.1.5-arch1-2 (linux@archlinux) fake image\n' \
		>"$r/boot/vmlinuz-linux"
	printf 'usr/lib/modules/7.1.5-arch1-2/kernel/fs/fat/vfat.ko.zst\n' \
		>"$r/boot/initramfs-linux.img"

	# A BIOS system has no /boot entry in fstab; /boot is just part of /.
	printf 'UUID=DEAD-BEEF\t/\text4\tdefaults\t0 1\n' >"$r/etc/fstab"

	printf '%s' "$r"
}

test_bios_guard_refuses_to_delete_real_kernel() {
	echo "TEST: SAFETY — BIOS/GRUB system without an ESP keeps its real kernel"
	local r out
	r="$(make_bios_root bios)"

	out="$(run_repair "$r")"

	assert_contains "explains why it refused" "$out" "this system booted via BIOS"
	assert_contains "names the override" "$out" "--esp DEVICE"
	assert_not_contains "does not claim shadows" "$out" "removed 2 shadow file"

	if [[ -f $r/boot/vmlinuz-linux ]]; then
		pass "real kernel image preserved"
	else
		fail "real kernel image preserved" "boot-repair deleted the only kernel!"
	fi
	if [[ -f $r/boot/initramfs-linux.img ]]; then
		pass "real initramfs preserved"
	else
		fail "real initramfs preserved" "boot-repair deleted the only initramfs!"
	fi
}

test_bios_guard_overridden_by_explicit_esp() {
	echo "TEST: --esp DEVICE overrides the BIOS guard"
	local r out
	r="$(make_bios_root biosesp)"

	# Naming the ESP by hand asserts the firmware assumption the guard checks,
	# so cleanup proceeds exactly as it would on a UEFI box.
	out="$(run_repair "$r" --esp /dev/fake1)"

	assert_not_contains "guard is silent" "$out" "this system booted via BIOS"
	assert_contains "treats the files as shadows" "$out" "orphaned kernel file"

	# initramfs-linux.img is not regenerated by a --root run, so its absence
	# proves the deletion happened. (vmlinuz-linux legitimately reappears:
	# sync_kernel_image reinstalls the target kernel straight afterwards.)
	if [[ ! -f $r/boot/initramfs-linux.img ]]; then
		pass "shadow initramfs deleted under --esp"
	else
		fail "shadow initramfs deleted under --esp" "guard did not yield to --esp"
	fi
}

# A UEFI fixture must keep behaving exactly as before — the guard must not
# change anything on kuhy's actual (UEFI) machine.
test_uefi_shadow_cleanup_still_works() {
	echo "TEST: REGRESSION — UEFI system still cleans shadow files"
	local r out
	r="$(make_root uefishadow)"
	rm -rf "${r:?}/boot"
	mkdir -p "$r/boot"
	printf 'Linux version 7.1.5-arch1-2 (linux@archlinux) fake\n' >"$r/boot/vmlinuz-linux"
	printf 'stale\n' >"$r/boot/initramfs-linux-fallback.img"

	out="$(run_repair "$r")"

	assert_not_contains "guard stays out of the way" "$out" "this system booted via BIOS"
	assert_contains "still detects shadows" "$out" "orphaned kernel file"
	if [[ ! -f $r/boot/initramfs-linux-fallback.img ]]; then
		pass "UEFI shadow deletion unchanged"
	else
		fail "UEFI shadow deletion unchanged" "guard blocked a legitimate cleanup"
	fi
}
